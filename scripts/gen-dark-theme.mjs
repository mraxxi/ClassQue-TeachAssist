#!/usr/bin/env node
/**
 * Generates src/dark-theme.css — the dark palette.
 *
 * Tailwind v4 utilities read their colours from CSS variables (`bg-stone-50` -> var(--color-stone-50)), so dark mode
 * is a *remap of those variables* under `:root[data-theme="dark"]`: no `dark:` class on any component, and `position:
 * fixed` modals keep working (unlike a CSS `filter: invert()`).
 *
 *  - neutrals (stone) and tint scales are re-lit by lightness, keeping each family's hue/chroma from the real theme
 *  - `white` becomes the card surface, so `bg-teal-800 text-white` stays a readable (pale) button with dark text
 *  - `.theme-original` / `.print-sheet` restore the original palette for intentionally dark blocks and paper previews
 *  - everything sits inside `@media screen`, so printing is always light
 *
 * Run:  node scripts/gen-dark-theme.mjs
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const theme = fs.readFileSync(path.join(root, 'node_modules/tailwindcss/theme.css'), 'utf8');
const FAMILIES = ['stone', 'teal', 'emerald', 'amber', 'rose', 'sky', 'blue', 'purple'];
const SHADES = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950];

const original = {};
for (const f of FAMILIES) for (const s of SHADES) {
  const m = theme.match(new RegExp(`--color-${f}-${s}:\\s*([^;]+);`));
  if (!m) throw new Error(`missing --color-${f}-${s}`);
  original[`${f}-${s}`] = m[1].trim();
}
const parse = (v) => { const m = v.match(/oklch\(\s*([\d.]+)%\s+([\d.]+)\s+([\d.]+)/); return m ? { l: +m[1], c: +m[2], h: +m[3] } : null; };

// Lightness (%) per shade in dark mode.
const L_STONE = { 50: 17.5, 100: 27, 200: 33, 300: 44, 400: 66, 500: 72, 600: 78, 700: 85, 800: 90, 900: 95, 950: 98 };
const L_TINT = { 50: 24, 100: 29, 200: 37, 300: 46, 400: 60, 500: 68, 600: 76, 700: 84, 800: 90, 900: 94, 950: 97 };
const C_TINT = { 50: 0.4, 100: 0.45, 200: 0.5, 300: 0.55, 400: 0.8, 500: 0.9, 600: 0.85, 700: 0.75, 800: 0.6, 900: 0.45, 950: 0.35 };

const dark = {};
for (const f of FAMILIES) {
  const base = parse(original[`${f}-500`]);
  for (const s of SHADES) {
    if (f === 'stone') {
      const o = parse(original[`${f}-${s}`]);
      dark[`${f}-${s}`] = `oklch(${L_STONE[s]}% ${o.c} ${o.h})`;
    } else {
      dark[`${f}-${s}`] = `oklch(${L_TINT[s]}% ${(base.c * C_TINT[s]).toFixed(3)} ${base.h})`;
    }
  }
}

const lines = (map, indent) => Object.entries(map).map(([k, v]) => `${indent}--color-${k}: ${v};`).join('\n');
const lightIsland = `
/* Dark blocks in LIGHT mode: the global stone-400/500 were darkened for AA on light surfaces, so restore the light greys here. */
.theme-original {
  --color-stone-400: ${original['stone-400']};
  --color-stone-500: ${original['stone-500']};
}
`;
const css = `/* GENERATED by scripts/gen-dark-theme.mjs from tailwindcss/theme.css — do not edit by hand. */
${lightIsland}
@media screen {
  :root[data-theme="dark"] {
    color-scheme: dark;
    --app-bg: oklch(12.5% 0.004 49);
    --app-fg: oklch(93% 0.003 49);
    --app-paper: oklch(17.5% 0.004 49);
    --color-white: oklch(21% 0.004 49);
    --color-black: oklch(96% 0.002 49);
${lines(dark, '    ')}
  }

  /* Intentionally dark blocks (hero, stopwatch, D1 card) and paper previews keep the ORIGINAL palette. */
  :root[data-theme="dark"] .theme-original,
  :root[data-theme="dark"] .print-sheet {
    color-scheme: light;
    --color-white: #fff;
    --color-black: #000;
${lines(original, '    ')}
  }
}
`;
fs.writeFileSync(path.join(root, 'src/dark-theme.css'), css);
console.log(`wrote src/dark-theme.css (${css.length} bytes)`);
